#!/usr/bin/env python3
"""Regenerate tests/golden/GAPS.md from the C baseline and a Rust capture.

    python3 -I tests/golden/check.py --out DIR
    python3 -I tests/golden/gaps.py DIR

DIR holds the Rust TSVs written by check.py --out. Rows compare text, IPA and
espeak phonemes; the table lists every language with at least one difference,
worst first, with three sample rows and a heuristic cause per sample.
"""
import os
import re
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
STRESS = re.compile("[ˈˌ'`,%=]")


def rows(path):
    with open(path, encoding="utf-8") as f:
        return [line.split("\t") for line in f.read().splitlines()]


def cause(c, r):
    if c == r:
        return "unknown"
    if not r.strip():
        return "port prints nothing where C speaks"
    if not c.strip():
        return "port speaks text that C skips"
    if ("(en)" in c) != ("(en)" in r):
        return "language-switch (en) fallback differs"
    if re.sub(r"\s+", "", c) == re.sub(r"\s+", "", r):
        return "word spacing or pauses"
    if STRESS.sub("", c) == STRESS.sub("", r):
        return "stress or tone-mark placement"
    if re.sub(r"[ˈˌ\s]", "", c).startswith(re.sub(r"[ˈˌ\s]", "", r)[:2]) and len(c) != len(r):
        return "rule or suffix handling (phoneme count differs)"
    return "phoneme rule difference"


def diff_rows(base, rust):
    out = []
    for b, r in zip(base, rust):
        if b == r:
            continue
        col = 1 if b[1] != r[1] else 2
        out.append((b[0], col, b[col], r[col]))
    return out


def esc(s):
    return s.replace("|", "\\|").replace("`", "'")[:90]


def main():
    out_dir = sys.argv[1]
    report = []
    for fn in sorted(os.listdir(os.path.join(HERE, "corpus"))):
        lang = fn[:-4]
        base = rows(os.path.join(HERE, "baseline", lang + ".tsv"))
        d = diff_rows(base, rows(os.path.join(out_dir, lang + ".tsv")))
        report.append((lang, len(base), d))
    report.sort(key=lambda t: (-len(t[2]) / t[1], t[0]))
    lines = [
        "# Golden gaps: Rust port vs C espeak-ng f0fb11a8",
        "",
        "Generated by `gaps.py`. `col` is `ipa` (`--ipa`) or `x` (`-x`); the sample shows the C value, then the port value.",
        "The cause column is a heuristic from the shape of the difference, not a root-cause analysis.",
        "",
    ]
    notes = os.path.join(HERE, "deviations.md")
    if os.path.exists(notes):
        with open(notes, encoding="utf-8") as f:
            lines += [f.read().rstrip(), ""]
    lines += ["## Differing rows per language", ""]
    lines += ["| language | rows | differing | % differing |", "|---|---|---|---|"]
    for lang, n, d in report:
        if d:
            lines.append(f"| {lang} | {n} | {len(d)} | {100 * len(d) / n:.1f} |")
    zero = [lang for lang, _, d in report if not d]
    total = sum(n for _, n, _ in report)
    bad = sum(len(d) for _, _, d in report)
    lines += ["", f"Zero differences: {', '.join(zero)}.", "", f"Total {total} rows, {bad} differing ({100 * bad / total:.1f}%).", ""]
    for lang, n, d in report:
        if not d:
            continue
        causes = Counter(cause(c, r) for _, _, c, r in d)
        lines += [f"## {lang}", "", f"{len(d)} of {n} rows differ ({100 * len(d) / n:.1f}%). Most common cause: {causes.most_common(1)[0][0]}.", "",
                  "| input | col | C | port | likely cause |", "|---|---|---|---|---|"]
        step = max(1, len(d) // 3)
        for text, col, c, r in d[::step][:3]:
            lines.append(f"| {esc(text)} | {'ipa' if col == 1 else 'x'} | {esc(c)} | {esc(r)} | {cause(c, r)} |")
        lines.append("")
    with open(os.path.join(HERE, "GAPS.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
